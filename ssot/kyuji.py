# 一対多・文脈依存で自動修正が危険な字（弁→辨/瓣/辯/辦、予→豫/予、余→餘/余、
# 欠→缺/欠、芸→藝/芸）は誤検出・誤置換を避けるため KYUJI_MAP に含めない。
# KYUJI_MAP との共通部分が無いことは不変条件（eval/test_kyuji.py で検査）。
# NB: 「従」は從へ一意に対応するため（曖昧でないため）この集合には入れない。
AMBIGUOUS_SHINJI: Set[str] = set("弁予余欠芸")

# str.translate 用に一度だけ構築（文字単位置換は文脈非依存＝ストリーム安全）
_TABLE = str.maketrans(KYUJI_MAP)

# 末尾解説の見出し。これ以降は新字体の*言及*が正当なので置換しない。
POINT_MARKER = "【ポイント】"


def to_kyuji(text: str) -> str:
    """新字体を旧字体へ置換する（1:1・文脈非依存）。"""
    return text.translate(_TABLE)


def to_kyuji_body(text: str) -> str:
    """完成テキスト用。【ポイント】以降は解説なので置換しない。"""
    i = text.find(POINT_MARKER)
    return to_kyuji(text) if i < 0 else to_kyuji(text[:i]) + text[i:]


def _hold_len(buf: str, marker: str) -> int:
    """buf の末尾が marker の真の接頭辞になつてゐる最長長さ（保留すべき文字数）。"""
    for n in range(min(len(marker) - 1, len(buf)), 0, -1):
        if marker.startswith(buf[-n:]):
            return n
    return 0


class KyujiStream:
    """ストリーミング用の状態付きトランスデューサ。

    feed() をトークン順に呼び、最後に flush() を呼ぶ。POINT_MARKER を検出したら
    以降は素通し（解説内の新字体は置換しない）。マーカーがトークン境界に跨いでも
    検出できるよう、マーカー長-1 文字までを内部に保留する。
    """

    def __init__(self, marker: str = POINT_MARKER) -> None:
        self.marker = marker
        self._buf = ""
        self._passthrough = False

    def feed(self, chunk: str) -> str:
        if self._passthrough:
            return chunk
        self._buf += chunk
        i = self._buf.find(self.marker)
        if i >= 0:                                  # 解説に到達 → 以降は素通し
            out = to_kyuji(self._buf[:i]) + self._buf[i:]
            self._buf = ""
            self._passthrough = True
            return out
        hold = _hold_len(self._buf, self.marker)     # マーカー途中の可能性を保留
        emit, self._buf = (self._buf[:len(self._buf) - hold],
                           self._buf[len(self._buf) - hold:])
        return to_kyuji(emit)

    def flush(self) -> str:
        rest, self._buf = self._buf, ""
        return rest if self._passthrough else to_kyuji(rest)


def kyuji_stream(tokens: Iterable[str], marker: str = POINT_MARKER) -> Iterator[str]:
    """トークン列を旧字体化しながら再ストリームする（空文字列は yield しない）。"""
    st = KyujiStream(marker)
    for tok in tokens:
        out = st.feed(tok)
        if out:
            yield out
    tail = st.flush()
    if tail:
        yield tail
